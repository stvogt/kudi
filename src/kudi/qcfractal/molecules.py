"""Molecule loading helpers for QCFractal submissions."""

from __future__ import annotations

import json
from pathlib import Path
from typing import Any

from ..models import Geometry, IrcPoint


def _require_qcel_models() -> Any:
    try:
        from qcelemental import models as qcel_models
    except ModuleNotFoundError as exc:
        raise ImportError(
            "qcelemental is required for molecule handling. "
            "Install with: pip install 'kudi[qcfractal]'"
        ) from exc
    return qcel_models


def molecule_from_json(path: Path | str):
    """Load a QCElemental Molecule from JSON data."""

    qcel_models = _require_qcel_models()
    input_path = Path(path)
    with input_path.open("r", encoding="utf-8") as handle:
        payload = json.load(handle)
    return qcel_models.Molecule(**payload)


def molecule_from_xyz(path: Path | str, *, charge: int = 0, multiplicity: int = 1):
    """Build a QCElemental Molecule from an XYZ file."""

    qcel_models = _require_qcel_models()
    xyz_path = Path(path)
    xyz_text = xyz_path.read_text(encoding="utf-8")
    return qcel_models.Molecule.from_data(
        xyz_text,
        molecular_charge=charge,
        molecular_multiplicity=multiplicity,
    )


def _geometry_to_xyz_text(geometry: Geometry) -> str:
    lines = [str(len(geometry.atoms)), "Generated by kudi.qcfractal.molecules"]
    for atom in geometry.atoms:
        lines.append(f"{atom.symbol} {atom.x} {atom.y} {atom.z}")
    return "\n".join(lines) + "\n"


def molecule_from_geometry(geometry: Geometry, *, charge: int = 0, multiplicity: int = 1):
    """Build a QCElemental Molecule from a Kudi Geometry object."""

    if not geometry.atoms:
        raise ValueError("Geometry has no atoms")

    qcel_models = _require_qcel_models()
    xyz_text = _geometry_to_xyz_text(geometry)
    return qcel_models.Molecule.from_data(
        xyz_text,
        molecular_charge=charge,
        molecular_multiplicity=multiplicity,
    )


def molecule_from_irc_point(point: IrcPoint, *, charge: int = 0, multiplicity: int = 1):
    """Build a QCElemental Molecule from one IRC point geometry."""

    if point.geometry is None:
        raise ValueError("IRC point has no geometry")
    return molecule_from_geometry(point.geometry, charge=charge, multiplicity=multiplicity)
